/** ক্যাটাগরি+সাব মিলিয়ে তথ্যের সংখ্যা (সাব-টাইলে "N টি তথ্য" দেখাতে) */
export function countInSub(categoryId: string, subId: string) {
  return services.filter((s) => s.category === categoryId && s.subcategory === subId).length;
}

/** ক্যাটাগরির ভেতর উপস্থিত ইউনিয়নগুলো — ফিল্টার চিপে */
export function unionsInCategory(categoryId: string) {
  const set = new Set<string>();
  services.forEach((s) => {
    if (s.category === categoryId) set.add(s.union);
  });
  return [...set];
}

